package operators;

public class RelationalOperator {
    static void main(String[] args) {
        int p =10 , q= 15;

        System.out.println(p == q);
        System.out.println(p!=q);
        System.out.println(p<q);
        System.out.println(p>q);
        System.out.println(p<=q);
        System.out.println(p>=q);



    }
}
